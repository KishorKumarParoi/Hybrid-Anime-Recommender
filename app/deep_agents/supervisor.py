"""
Anime CTO Supervisor & Master Orchestrator
Formulates dynamic DAG task plans and synthesizes executive intelligence dossiers.
"""
import time
import logging
from typing import Dict, Any, List
from app.deep_agents.state import DeepAnimeAgentState

logger = logging.getLogger("AnimeCTOSupervisor")


async def supervisor_planner_node(state: DeepAnimeAgentState) -> Dict[str, Any]:
    """
    Analyzes user intent, initializes telemetry, and formulates the dynamic task plan.
    """
    topic = state.get("topic", "")
    logger.info(f"👑 [CTO Supervisor] Formulating dynamic execution plan for topic: '{topic}'")

    # Formulate dynamic task DAG
    plan = [
        "safety_guardrail",
        "persona_profiler",
        "catalog_discovery",
        "quality_critic",
        "cto_gate",
        "supervisor_synthesizer",
    ]

    telemetry = {
        "start_time": time.time(),
        "planned_tasks": plan,
        "agents_invoked": ["supervisor_planner"],
    }

    return {
        "task_plan": plan,
        "telemetry": telemetry,
        "iteration_count": state.get("iteration_count", 0),
        "max_iterations": state.get("max_iterations", 2),
    }


async def supervisor_synthesizer_node(state: DeepAnimeAgentState) -> Dict[str, Any]:
    """
    Compiles all sub-agent deliverables into a comprehensive, publication-ready executive dossier.
    """
    # If safety intercepted or already completed
    if state.get("final_dossier") and state.get("loop_status") == "REJECTED":
        return {"final_dossier": state["final_dossier"]}

    topic = state.get("topic", "Anime Recommendation")
    persona = state.get("persona_profile", {})
    candidates = state.get("candidate_anime", [])
    lineage = state.get("studio_lineage", [])
    critic = state.get("critic_evaluation", {})
    cto = state.get("cto_decision", {})
    telemetry = state.get("telemetry", {})

    elapsed_ms = round((time.time() - telemetry.get("start_time", time.time())) * 1000, 2)
    telemetry["execution_latency_ms"] = elapsed_ms

    # Construct Markdown Dossier
    lines: List[str] = [
        f"# 👑 Executive Anime Intelligence Dossier: {topic.title()}",
        f"**Generated by:** Industrial-Grade Deep Multi-Agent Mesh (LangGraph + CTO Governance)",
        f"**Execution Latency:** {elapsed_ms}ms | **Critic Iterations:** {state.get('iteration_count', 1)}",
        "",
        "---",
        "",
        "## 👤 Persona Taste Profile & Affinity Vector",
        f"- **Target Tone:** `{persona.get('target_tone', 'balanced')}`",
        f"- **Pacing Preference:** `{persona.get('pacing_preference', 'moderate')}`",
        f"- **Aesthetic Vibe:** `{persona.get('aesthetic', 'modern_prestige')}`",
        f"- **Content Tier:** `{persona.get('content_rating_ok', 'PG-13')}`",
        f"- **Priority Genres:** {', '.join(persona.get('preferred_genres', ['Drama', 'Action']))}",
        "",
        "---",
        "",
        "## 🎬 Curated Master Recommendations",
        "",
        "| Title | Studio | Score | Match % | Streaming Legal Rights | Primary Vibe |",
        "|---|---|---|---|---|---|",
    ]

    for c in candidates:
        platforms = ", ".join(c.get("streaming_platforms", ["Crunchyroll"]))
        lines.append(
            f"| **{c.get('title')}** | {c.get('studio')} | ⭐ {c.get('score')} | "
            f"🎯 {int(c.get('match_rate', 0.85) * 100)}% | {platforms} | {c.get('vibe')} |"
        )

    lines.extend([
        "",
        "### In-Depth Synopsis & Recommender Rationale",
    ])

    for idx, c in enumerate(candidates, 1):
        lines.extend([
            f"#### {idx}. {c.get('title')} ({c.get('studio')})",
            f"> {c.get('synopsis')}",
            f"- **Why You Should Watch:** {c.get('relevance_reason')}",
            "",
        ])

    lines.extend([
        "---",
        "",
        "## 🧬 Studio Lineage & Creative Genealogy",
    ])

    for item in lineage:
        lines.append(f"- **{item.get('title')}** → *{item.get('lineage')}*")

    lines.extend([
        "",
        "---",
        "",
        "## ⚖️ Quality Critic Audit Trail (Self-Reflective Loop)",
        f"- **Composite Quality Score:** `{critic.get('score', 85.0)}/100`",
        f"- **Relevance Alignment:** `{critic.get('relevance_score', 90.0)}%`",
        f"- **Catalog Diversity:** `{critic.get('diversity_score', 80.0)}%`",
        f"- **Hallucination Detected:** `{'Yes' if critic.get('hallucination_detected') else 'No (Zero Detected)'}`",
        f"- **Loop Status:** `{critic.get('loop_status', 'APPROVED')}`",
    ])

    if critic.get("feedback"):
        lines.append("- **Critic Feedback Notes:**")
        for fb in critic.get("feedback", []):
            lines.append(f"  - {fb}")

    lines.extend([
        "",
        "---",
        "",
        "## 🎖️ Chief Taste Officer (CTO) & Governance Gate",
        f"- **Curator Status:** `{cto.get('status', 'APPROVED')}`",
        f"- **Executive Sign-Off:** `{cto.get('signoff_by', 'ChiefTasteOfficer-AI')}`",
        f"- **Editorial Review:** {cto.get('editorial_notes', 'All rights verified.')}",
    ])

    if cto.get("break_glass_token"):
        lines.extend([
            f"- **⚠️ Break-Glass Token:** `{cto.get('break_glass_token')}` *(Human-in-the-Loop Override Required)*",
        ])

    dossier = "\n".join(lines)
    logger.info("👑 [CTO Supervisor] Final Executive Dossier compiled successfully.")

    return {
        "final_dossier": dossier,
        "telemetry": telemetry,
    }
